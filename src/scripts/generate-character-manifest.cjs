#!/usr/bin/env node
/**
 * Generate src/assets/characterManifest.ts with static require() calls
 * for all character layer assets under src/assets/characters.
 */
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..', '..')
const SRC_ASSETS = path.join(ROOT, 'src', 'assets', 'characters')
const OUT_PATH = path.join(ROOT, 'src', 'assets', 'characterManifest.ts')
const exts = new Set(['.png', '.jpg', '.jpeg', '.webp', '.svg'])

function walk(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
  let files = []
  for (const e of entries) {
    const full = path.join(dir, e.name)
    if (e.isDirectory()) files = files.concat(walk(full))
    else if (exts.has(path.extname(e.name).toLowerCase())) files.push(full)
  }
  return files
}

function main() {
  if (!fs.existsSync(SRC_ASSETS)) {
    console.error('Character assets not found at', SRC_ASSETS)
    process.exit(1)
  }
  const files = walk(SRC_ASSETS)
  const byLayer = new Map()
  for (const file of files) {
    const rel = path.relative(SRC_ASSETS, file)
    const parts = rel.split(path.sep)
    const layer = parts[0]?.toUpperCase?.()
    if (!layer) continue
    const arr = byLayer.get(layer) ?? []
    arr.push(rel)
    byLayer.set(layer, arr)
  }
  // sort for stability
  for (const [k, arr] of byLayer) {
    arr.sort((a, b) => a.localeCompare(b))
    byLayer.set(k, arr)
  }

  const lines = []
  lines.push('// auto-generated by scripts/generate-character-manifest.cjs')
  lines.push("import { ImageSourcePropType } from 'react-native'")
  lines.push('export type CharacterManifest = Record<string, ImageSourcePropType[]>')
  lines.push('const manifest: CharacterManifest = {')
  for (const [layer, arr] of [...byLayer.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    lines.push(`  ${JSON.stringify(layer)}: [`)
    for (const rel of arr) {
      const requirePath = './characters/' + rel.split(path.sep).join('/')
      lines.push(`    require(${JSON.stringify(requirePath)}),`)
    }
    lines.push('  ],')
  }
  lines.push('}')
  lines.push('export default manifest')

  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true })
  fs.writeFileSync(OUT_PATH, lines.join('\n'))
  console.log('Wrote manifest with', files.length, 'files to', path.relative(ROOT, OUT_PATH))
}

main()
